"""AT-45 service acceptance against Python or the actual packaged executable."""
import argparse
from contextlib import closing
import json
import os
from pathlib import Path
import shutil
import sqlite3
import subprocess
import sys
import tempfile
import uuid

ROOT = Path(__file__).resolve().parents[1]
METHOD = 'amphibole.oxygen23'
VERSION = '0.1.0'


def verify_service(executable=None):
    command = [str(executable.resolve())] if executable else [sys.executable, '-m', 'petrolab.ndjson_service']
    environment = {**os.environ, 'PYTHONUTF8': '1', 'PYTHONIOENCODING': 'utf-8',
                   'PYTHONPATH': str(ROOT / 'src')}
    with tempfile.TemporaryDirectory(prefix='petrolab-amphibole-') as folder, tempfile.TemporaryFile() as errors:
        project = Path(folder) / 'project.sqlite'
        service = subprocess.Popen(command, cwd=ROOT, env=environment, stdin=subprocess.PIPE,
                                   stdout=subprocess.PIPE, stderr=errors, text=True, encoding='utf-8')
        try:
            def send(operation, payload, error_code=None):
                request_id = str(uuid.uuid4())
                service.stdin.write(json.dumps({'protocol_version': '1.0', 'request_id': request_id,
                                               'command': operation, 'payload': payload}) + '\n')
                service.stdin.flush()
                line = service.stdout.readline()
                if not line:
                    errors.seek(0)
                    raise AssertionError(f'Service stopped during {operation}: {errors.read().decode("utf-8", errors="replace")}')
                response = json.loads(line)
                assert response['request_id'] == request_id, response
                if error_code:
                    assert response.get('error', {}).get('code') == error_code, response
                    return response
                assert 'error' not in response, response
                return response['result']

            sources = []
            for name in ('amphibole_tn8.csv', 'amphibole_unsupported_f.csv'):
                source = Path(folder) / name
                shutil.copyfile(ROOT / 'fixtures/formula' / name, source)
                sources.append((source, source.read_bytes()))
                workspace = send('import.workspace.create', {'sources': [{'staged_path': str(source)}]})
                send('import.plan.apply', {'project_database_path': str(project),
                     'source_path': str(source), 'recipe': workspace['active']['recipe']})
            records = send('project.mineral_identification.list', {'project_database_path': str(project)})['identifications']
            analyses = send('project.analyses.list', {'project_database_path': str(project)})['analyses']
            ids = {record['identity']['Analysis']: record['analysis_id'] for record in analyses}
            assert set(ids) == {'Amp-TN8', 'Amp-F'}, ids
            parameters = {'fe_mode': 'all_fe2'}
            payload = {'project_database_path': str(project), 'analysis_ids': [ids['Amp-TN8']],
                       'method_id': METHOD, 'method_version': VERSION, 'parameters': parameters}
            assert not send('formula.preview', payload)['can_save']
            for record in records:
                send('project.mineral_assignment.decide', {'project_database_path': str(project),
                     'analysis_id': record['analysis_id'], 'target': 'tremolite',
                     'input_fingerprint': record['input_fingerprint'], 'ruleset_version': record['ruleset_version'],
                     'reason': 'AT-45: explicit calcic-amphibole assignment'})

            catalog = send('formula.methods.list', {'accepted_assignment': 'tremolite'})['methods']
            assert [(method['method_id'], method['version']) for method in catalog] == [(METHOD, VERSION)], catalog
            with closing(sqlite3.connect(project)) as connection, connection:
                measured_before = connection.execute('SELECT * FROM measurement ORDER BY rowid').fetchall()

            preview = send('formula.preview', payload)
            assert preview['can_save'] and preview['method']['status'] == 'draft', preview
            result = preview['results'][0]
            # Independent published Table 2 values, not generated by this algorithm.
            for field, expected in {'Si_apfu': 8.0, 'Mg_apfu': 4.4, 'Ca_apfu': 1.6, 'Ni_apfu': 1.0}.items():
                assert abs(result['values'][field] - expected) <= .1, (field, result['values'][field])
            assert abs(result['values']['oxide_total'] - 99.8) < 1e-10
            assert not {'OH_est_apfu', 'OH_apfu', 'F_apfu', 'Cl_apfu', 'Fe3_apfu'} & result['values'].keys()
            assert any('Железо не измерено' in warning for warning in result['warnings'])

            mixed = send('formula.preview', {**payload, 'analysis_ids': [ids['Amp-TN8'], ids['Amp-F']]})
            assert not mixed['can_save']
            assert [row['analysis_id'] for row in mixed['results']] == [ids['Amp-TN8'], ids['Amp-F']]
            assert mixed['results'][0]['status'] == 'current'
            assert mixed['results'][1]['status'] == 'failed' and not mixed['results'][1]['values']
            assert any('F: не поддерживается' in error for error in mixed['results'][1]['errors'])
            send('formula.save', {**payload, 'analysis_ids': mixed['analysis_ids'],
                 'preview_fingerprint': mixed['input_fingerprint']}, 'FORMULA_INPUT_INVALID')
            with closing(sqlite3.connect(project)) as connection, connection:
                assert connection.execute('SELECT count(*) FROM formula_run').fetchone()[0] == 0
                assert connection.execute('SELECT count(*) FROM formula_derived_value').fetchone()[0] == 0

            save_payload = {**payload, 'preview_fingerprint': preview['input_fingerprint']}
            saved = send('formula.save', save_payload)
            retry = send('formula.save', save_payload)
            assert retry['reused'] and retry['run']['id'] == saved['run']['id']
            history = send('formula.runs.list', {'project_database_path': str(project), 'analysis_id': ids['Amp-TN8']})['runs']
            assert len(history) == 1 and history[0]['run']['status'] == 'current'
            assert history[0]['run']['result_manifest']['results'][0]['values'] == result['values']
            used = {measurement['measurement_id'] for measurement in result['used']}
            assert used and set(saved['run']['input_measurement_ids']) == used
            for value in history[0]['derived_values']:
                assert set(value['input_measurement_ids']) == used
                assert value['method_id'] == METHOD and value['method_version'] == VERSION
                assert value['unit'] == ('wt.%' if value['field'] == 'oxide_total' else 'apfu')
            with closing(sqlite3.connect(project)) as connection, connection:
                assert connection.execute('SELECT * FROM measurement ORDER BY rowid').fetchall() == measured_before
                stored = connection.execute('SELECT payload_json FROM formula_run').fetchone()[0]
                # Deliberate input change only in this disposable QA database.
                connection.execute("UPDATE measurement SET raw_token='20' WHERE analysis_id=? AND canonical_field='MgO'", (ids['Amp-TN8'],))
            send('formula.save', save_payload, 'FORMULA_PREVIEW_STALE')
            stale = send('formula.runs.list', {'project_database_path': str(project), 'analysis_id': ids['Amp-TN8']})['runs'][0]
            assert stale['run']['status'] == 'stale' and stale['run']['stale_reasons']
            assert all(value['status'] == 'stale' for value in stale['derived_values'])
            assert stale['run']['result_manifest']['results'][0]['values'] == result['values']
            with closing(sqlite3.connect(project)) as connection, connection:
                assert connection.execute('SELECT payload_json FROM formula_run').fetchone()[0] == stored
                assert connection.execute('PRAGMA integrity_check').fetchone()[0] == 'ok'
            assert all(source.read_bytes() == original for source, original in sources)
            return {'method': f'{METHOD}/{VERSION}', 'checks': ['explicit assignment', 'published APFU',
                    'unsupported F and atomic rejection', 'idempotent save and reopened history',
                    'Measurement provenance and unchanged inputs', 'stale result and immutable history',
                    'unchanged source files'], 'service': 'packaged' if executable else 'python'}
        finally:
            service.stdin.close()
            try:
                service.wait(timeout=15)
            except subprocess.TimeoutExpired:
                service.kill()
                service.wait(timeout=5)
            service.stdout.close()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--executable', type=Path)
    args = parser.parse_args()
    print(json.dumps(verify_service(args.executable), ensure_ascii=False, indent=2))
